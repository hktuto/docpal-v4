

export const twipToPx = (twip: number) => {
  return twip / 15
}

export const pxToTwip = (px: number) => {
  return px * 15
}


export const twipToCm = (twip: number) => {
  return twip / 566.92913386
}
export const cmToTwip = (cm: number) => {
  return cm * 566.92913386
}

export const twipToInch = (twip: number) => {
  return twip / 1440
}
export const inchToTwip = (inch: number) => {
  return inch * 1440
}
